"""
Assessment data model for Stage 4 report generation.

Design principles
-----------------
* ``data_source`` is always supplied explicitly by the caller.
  It is never inferred from file names, paths, or packet content.
* Properties on this model are pure computations over already-extracted
  data; no additional parsing or rule evaluation happens here.
* ``None`` / absent fields in ``NetworkFeatures`` propagate faithfully;
  nothing is invented during report construction.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from wsa.analysis.feature_set import NetworkFeatures, ScanFeatures
from wsa.rules.finding import Finding, SEVERITY_ORDER

# ---------------------------------------------------------------------------
# Severity constants (reused in reporters)
# ---------------------------------------------------------------------------

SEVERITIES: List[str] = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]

# Risk score contribution per finding severity.
# These are heuristic weights chosen to surface critical issues clearly.
RISK_SCORES: Dict[str, int] = {
    "CRITICAL": 40,
    "HIGH":     15,
    "MEDIUM":   5,
    "LOW":      2,
    "INFO":     0,
}

# ---------------------------------------------------------------------------
# Provenance notes (keyed by data_source string)
# ---------------------------------------------------------------------------

_DATA_SOURCE_NOTES: Dict[str, str] = {
    "pcap_offline": (
        "Generated by the offline PCAP/PCAPNG assessment pipeline. "
        "This capture is not a live-monitoring session."
    ),
    "virtual_lab": (
        "Generated from observed traffic on an isolated virtual wireless lab. "
        "No external wireless network was attacked."
    ),
    "real_lab": (
        "Generated from observed traffic on an explicitly authorized lab network. "
        "This source is not inferred from packet content."
    ),
    "simulated": (
        "Generated from synthetic test data produced by the WSA PCAP generator. "
        "Findings describe characteristics of artificial captures and do not "
        "reflect any real wireless environment."
    ),
    "real": (
        "Generated from a supplied wireless packet capture. "
        "Provenance of the capture file has not been independently verified."
    ),
}


def data_source_note(data_source: str) -> str:
    """Return a human-readable provenance note for *data_source*."""
    return _DATA_SOURCE_NOTES.get(
        data_source,
        f"Data source label is '{data_source}'. Provenance has not been verified.",
    )


# ---------------------------------------------------------------------------
# NetworkAssessment
# ---------------------------------------------------------------------------

@dataclass
class NetworkAssessment:
    """
    Assessment result for one access point (one BSSID).

    Pairs the extracted ``NetworkFeatures`` from Stage 2 with the
    ``Finding`` list produced by the Stage 3 rule engine.
    """

    network: NetworkFeatures
    """Extracted RF / security features for this BSSID."""

    findings: List[Finding]
    """Security findings produced by the rule engine for this network."""

    @property
    def risk_score(self) -> int:
        """
        Aggregate heuristic risk score: sum of per-finding weights.

        Weights: CRITICAL=40, HIGH=15, MEDIUM=5, LOW=2, INFO=0.
        Returns 0 for networks with no findings.
        """
        return sum(RISK_SCORES.get(f.severity, 0) for f in self.findings)

    @property
    def severity_counts(self) -> Dict[str, int]:
        """Count of findings per severity level (all five levels always present)."""
        counts: Dict[str, int] = {s: 0 for s in SEVERITIES}
        for f in self.findings:
            if f.severity in counts:
                counts[f.severity] += 1
        return counts

    @property
    def highest_severity(self) -> Optional[str]:
        """
        Severity label of the most severe finding, or ``None`` if there are none.

        Uses ``SEVERITY_ORDER`` for comparison so the ordering is consistent
        with the rest of the application.
        """
        if not self.findings:
            return None
        return min(
            self.findings,
            key=lambda f: SEVERITY_ORDER.get(f.severity, 99),
        ).severity


# ---------------------------------------------------------------------------
# Assessment
# ---------------------------------------------------------------------------

@dataclass
class Assessment:
    """
    Complete assessment of one PCAP capture session.

    Aggregates scan metadata (from ``ScanFeatures``) with per-network
    assessments (``NetworkAssessment`` list) that pair extracted network
    features with rule-engine findings.
    """

    source_file: str
    """Path or filename of the PCAP supplied by the caller."""

    data_source: str
    """
    Provenance label: ``'simulated'`` or ``'real'``.

    Always supplied by the caller; never inferred from file content.
    """

    analysis_timestamp: str
    """ISO 8601 timestamp (UTC) when the assessment was generated."""

    total_frames: int
    """Total packets returned by the PCAP reader."""

    total_networks: int
    """Number of unique BSSIDs discovered."""

    total_probe_requests: int
    """Total probe-request frames in the capture."""

    total_deauth_frames: int
    """Total deauth / disassoc frames in the capture."""

    total_eapol_frames: int
    """Total EAPOL frames in the capture."""

    parse_errors: List[str]
    """Non-fatal errors recorded during PCAP loading or frame parsing."""

    network_assessments: List[NetworkAssessment] = field(default_factory=list)
    """One entry per unique BSSID, in the order returned by ``extract_networks``."""

    # ------------------------------------------------------------------
    # Aggregate properties
    # ------------------------------------------------------------------

    @property
    def all_findings(self) -> List[Finding]:
        """Flat list of every finding across all networks."""
        return [f for na in self.network_assessments for f in na.findings]

    @property
    def finding_count(self) -> int:
        """Total number of findings across all networks."""
        return len(self.all_findings)

    @property
    def total_risk_score(self) -> int:
        """Sum of risk scores across all network assessments."""
        return sum(na.risk_score for na in self.network_assessments)

    @property
    def severity_counts(self) -> Dict[str, int]:
        """Count of all findings per severity level (all five levels present)."""
        counts: Dict[str, int] = {s: 0 for s in SEVERITIES}
        for f in self.all_findings:
            if f.severity in counts:
                counts[f.severity] += 1
        return counts


# ---------------------------------------------------------------------------
# Factory functions
# ---------------------------------------------------------------------------

def build_assessment(
    scan: ScanFeatures,
    engine_results: List[Tuple[NetworkFeatures, List[Finding]]],
    analysis_timestamp: Optional[str] = None,
) -> Assessment:
    """
    Construct an ``Assessment`` from a parsed scan and rule engine results.

    Parameters
    ----------
    scan : ScanFeatures
        Aggregate scan metadata produced by Stage 2 extraction.
    engine_results : list
        Output of ``RuleEngine.evaluate_scan(scan)`` — a list of
        ``(NetworkFeatures, List[Finding])`` pairs.
    analysis_timestamp : str | None
        ISO 8601 timestamp string.  Defaults to the current UTC time.

    Returns
    -------
    Assessment
        A fully populated assessment ready for report generation.
    """
    if analysis_timestamp is None:
        analysis_timestamp = datetime.now(timezone.utc).isoformat()

    return Assessment(
        source_file=scan.source_file,
        data_source=scan.data_source,
        analysis_timestamp=analysis_timestamp,
        total_frames=scan.total_frames,
        total_networks=scan.network_count,
        total_probe_requests=scan.total_probe_requests,
        total_deauth_frames=scan.total_deauth_frames,
        total_eapol_frames=scan.total_eapol_frames,
        parse_errors=list(scan.parse_errors),
        network_assessments=[
            NetworkAssessment(network=net, findings=findings)
            for net, findings in engine_results
        ],
    )


def assess_pcap(
    file_path: str,
    data_source: str,
    rules_dir: Optional[Path] = None,
    analysis_timestamp: Optional[str] = None,
) -> Assessment:
    """
    Full pipeline convenience function: load → parse → extract → evaluate → assess.

    Parameters
    ----------
    file_path : str
        Path to the PCAP / PCAPNG file.
    data_source : str
        Provenance label.  Must be ``'simulated'`` or ``'real'``.
        This value is **never inferred** from the file; it is the caller's
        responsibility to supply the correct label.
    rules_dir : Path | None
        Override for the rule YAML directory.  Defaults to the project
        ``rules/`` directory (auto-detected by ``RuleEngine``).
    analysis_timestamp : str | None
        Fixed timestamp for reproducible tests.  Defaults to current UTC time.

    Returns
    -------
    Assessment
    """
    # Lazy imports keep this module importable without triggering the full
    # parsing / scapy stack on every import.
    from wsa.ingestion.pcap_reader import load_pcap
    from wsa.ingestion.frame_parser import parse_frames
    from wsa.analysis.beacon_extractor import extract_networks
    from wsa.rules.engine import RuleEngine

    pkts, load_warnings = load_pcap(file_path)
    pf = parse_frames(pkts)
    networks = extract_networks(
        pf.beacon_frames, pf.deauth_frames, pf.eapol_frames
    )

    scan = ScanFeatures(
        source_file=file_path,
        data_source=data_source,
        total_frames=len(pkts),
        networks=networks,
        total_probe_requests=len(pf.probe_requests),
        total_deauth_frames=len(pf.deauth_frames),
        total_eapol_frames=len(pf.eapol_frames),
        parse_errors=load_warnings,
    )

    engine = RuleEngine(rules_dir)
    engine_results = engine.evaluate_scan(scan)

    return build_assessment(scan, engine_results, analysis_timestamp)
